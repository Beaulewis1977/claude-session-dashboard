// Defensive parsing of Claude Code session JSONL files.
//
// The format changes between Claude Code versions, so every field is optional
// and every line is validated on its own. Lines that are not valid JSON objects
// are skipped and counted.

import type { ChatMessage, ContentBlock, ToolResult } from './types'
import { toolLabel } from './tools'

export type RawEvent = Record<string, unknown>

export interface ParsedJsonl {
  events: RawEvent[]
  malformedLines: number
}

export function parseJsonl(text: string): ParsedJsonl {
  const events: RawEvent[] = []
  let malformedLines = 0
  // Strip a UTF-8 BOM if present.
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1)
  for (const rawLine of text.split('\n')) {
    const line = rawLine.trim()
    if (!line) continue
    try {
      const value: unknown = JSON.parse(line)
      if (value && typeof value === 'object' && !Array.isArray(value)) {
        events.push(value as RawEvent)
      } else {
        malformedLines++
      }
    } catch {
      malformedLines++
    }
  }
  return { events, malformedLines }
}

// ---------------------------------------------------------------------------
// Small typed accessors

export function str(v: unknown): string | undefined {
  return typeof v === 'string' && v.length > 0 ? v : undefined
}

function obj(v: unknown): Record<string, unknown> | undefined {
  return v && typeof v === 'object' && !Array.isArray(v)
    ? (v as Record<string, unknown>)
    : undefined
}

function validTimestamp(v: unknown): string | undefined {
  const s = str(v)
  if (!s) return undefined
  const t = Date.parse(s)
  return Number.isNaN(t) ? undefined : new Date(t).toISOString()
}

function messageOf(e: RawEvent): Record<string, unknown> | undefined {
  return obj(e.message)
}

/** Content of an event's message: a string, an array of blocks, or undefined. */
function contentOf(e: RawEvent): unknown {
  const m = messageOf(e)
  if (m && 'content' in m) return m.content
  // Some very old formats put content at the top level.
  if ('content' in e && e.type !== 'system') return e.content
  return undefined
}

function roleOf(e: RawEvent): string | undefined {
  return str(e.type) ?? str(messageOf(e)?.role)
}

// ---------------------------------------------------------------------------
// User prompt classification

const COMMAND_RE = /<command-name>([\s\S]*?)<\/command-name>/
const COMMAND_ARGS_RE = /<command-args>([\s\S]*?)<\/command-args>/
const COMMAND_OUTPUT_RE =
  /<(local-command-stdout|local-command-stderr|bash-stdout|bash-stderr)>([\s\S]*?)<\/\1>/

export type UserTextKind = 'prompt' | 'command' | 'command-output' | 'noise'

export function classifyUserText(text: string): { kind: UserTextKind; text: string } {
  const t = text.trim()
  if (!t) return { kind: 'noise', text: '' }
  const cmd = COMMAND_RE.exec(t)
  if (cmd) {
    const args = COMMAND_ARGS_RE.exec(t)?.[1]?.trim()
    const name = cmd[1].trim()
    return { kind: 'command', text: args ? `${name} ${args}` : name }
  }
  const out = COMMAND_OUTPUT_RE.exec(t)
  if (out) return { kind: 'command-output', text: out[2].trim() }
  if (t.startsWith('<command-message>') || t.startsWith('<local-command')) {
    return { kind: 'noise', text: '' }
  }
  if (/^\[Request interrupted by user/.test(t)) return { kind: 'noise', text: t }
  if (
    t.startsWith(
      'Caveat: The messages below were generated by the user while running local commands'
    )
  ) {
    return { kind: 'noise', text: '' }
  }
  return { kind: 'prompt', text: t }
}

function textFromBlocks(content: unknown): string {
  if (typeof content === 'string') return content
  if (!Array.isArray(content)) return ''
  return content
    .map((b) => {
      const o = obj(b)
      return o && o.type === 'text' && typeof o.text === 'string' ? o.text : ''
    })
    .filter(Boolean)
    .join('\n\n')
}

function toolResultOf(block: Record<string, unknown>, event?: RawEvent): ToolResult {
  let text = ''
  let images = 0
  const c = block.content
  if (typeof c === 'string') text = c
  else if (Array.isArray(c)) {
    const parts: string[] = []
    for (const item of c) {
      const o = obj(item)
      if (!o) continue
      if (o.type === 'text' && typeof o.text === 'string') parts.push(o.text)
      else if (o.type === 'image') images++
    }
    text = parts.join('\n')
  } else if (c != null) {
    text = JSON.stringify(c, null, 2)
  }
  // Older/newer versions sometimes carry a richer copy in `toolUseResult`.
  if (!text && event) {
    const tur = event.toolUseResult
    if (typeof tur === 'string') text = tur
  }
  return { text, isError: block.is_error === true, ...(images ? { images } : {}) }
}

function isSidechain(e: RawEvent): boolean {
  return e.isSidechain === true
}

// ---------------------------------------------------------------------------
// Summary analysis

export interface SessionAnalysis {
  sessionId?: string
  cwd?: string
  gitBranch?: string
  version?: string
  summary?: string
  firstPrompt?: string
  startedAt?: string
  lastActivityAt?: string
  userMessageCount: number
  assistantMessageCount: number
  toolCallCount: number
  models: string[]
  /** Plain text of the conversation, for full-text search. */
  searchText: string
  /** uuid of the first real prompt. Forks and branches keep it, so it groups a family. */
  firstUuid?: string
  /** Set when the file was made by Claude Code's `/branch` (or by this app's "Branch from here"). */
  forkedFrom?: ForkedFrom
}

export interface ForkedFrom {
  sessionId: string
  /** uuid of the last copied entry. */
  messageUuid?: string
  /** Id of the transcript message that entry belongs to. */
  messageId?: string
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

export function isUuid(v: unknown): v is string {
  return typeof v === 'string' && UUID_RE.test(v)
}

/** A user event that holds only tool results (part of the assistant's flow, not a prompt). */
export function isToolResultOnly(e: RawEvent): boolean {
  const c = contentOf(e)
  return Array.isArray(c) && c.length > 0 && c.every((b) => obj(b)?.type === 'tool_result')
}

const SEARCH_TEXT_LIMIT = 400_000

export function analyzeEvents(events: RawEvent[]): SessionAnalysis {
  const a: SessionAnalysis = {
    userMessageCount: 0,
    assistantMessageCount: 0,
    toolCallCount: 0,
    models: [],
    searchText: ''
  }
  const models = new Set<string>()
  const assistantIds = new Set<string>()
  const textParts: string[] = []
  let textLength = 0
  let minT = Infinity
  let maxT = -Infinity
  // Id of the transcript message the current event belongs to (see buildMessages).
  let messageStart: string | undefined
  let assistantMsgId: string | undefined

  const pushText = (t: string): void => {
    if (textLength >= SEARCH_TEXT_LIMIT || !t) return
    textParts.push(t)
    textLength += t.length + 1
  }

  for (const e of events) {
    const type = str(e.type)
    const ts = validTimestamp(e.timestamp)
    if (ts) {
      const t = Date.parse(ts)
      if (t < minT) minT = t
      if (t > maxT) maxT = t
    }
    if (!a.sessionId) a.sessionId = str(e.sessionId) ?? str(e.session_id)
    if (!a.cwd) a.cwd = str(e.cwd)
    const branch = str(e.gitBranch)
    if (branch) a.gitBranch = branch
    const version = str(e.version)
    if (version) a.version = version

    if (type === 'summary') {
      const s = str(e.summary)
      if (s) a.summary = s.trim()
      continue
    }
    if (isSidechain(e)) continue

    const uuid = str(e.uuid)
    if (uuid && type === 'assistant') {
      const mid = str(messageOf(e)?.id)
      if (!mid || mid !== assistantMsgId) messageStart = uuid
      assistantMsgId = mid
    } else if (uuid && type === 'user' && e.isMeta !== true && !isToolResultOnly(e)) {
      messageStart = uuid
      assistantMsgId = undefined
    }
    const ff = obj(e.forkedFrom)
    const ffSession = str(ff?.sessionId)
    if (ffSession) {
      a.forkedFrom = {
        sessionId: ffSession,
        messageUuid: str(ff?.messageUuid) ?? uuid,
        messageId: messageStart
      }
    }

    const role = roleOf(e)
    if (role === 'user' && type !== 'system') {
      if (e.isMeta === true || e.isCompactSummary === true) continue
      const content = contentOf(e)
      const text = textFromBlocks(content)
      if (!text) continue // e.g. tool results only
      const c = classifyUserText(text)
      if (c.kind === 'prompt') {
        a.userMessageCount++
        if (!a.firstPrompt) {
          a.firstPrompt = c.text
          a.firstUuid = uuid
        }
        pushText(c.text)
      }
    } else if (role === 'assistant') {
      const m = messageOf(e)
      const id = str(m?.id) ?? str(e.uuid)
      const model = str(m?.model)
      if (model && model !== '<synthetic>') models.add(model)
      const content = contentOf(e)
      if (id) {
        if (!assistantIds.has(id)) {
          assistantIds.add(id)
          a.assistantMessageCount++
        }
      } else {
        a.assistantMessageCount++
      }
      if (typeof content === 'string') pushText(content)
      else if (Array.isArray(content)) {
        for (const b of content) {
          const o = obj(b)
          if (!o) continue
          if (o.type === 'text' && typeof o.text === 'string') pushText(o.text)
          else if (o.type === 'tool_use') {
            a.toolCallCount++
            pushText(toolLabel(str(o.name) ?? 'tool', o.input))
          }
        }
      }
    }
  }

  if (minT !== Infinity) a.startedAt = new Date(minT).toISOString()
  if (maxT !== -Infinity) a.lastActivityAt = new Date(maxT).toISOString()
  a.models = [...models]
  a.searchText = textParts.join('\n').slice(0, SEARCH_TEXT_LIMIT)
  return a
}

// ---------------------------------------------------------------------------
// Chat transcript

function blocksFromAssistantContent(content: unknown, cwd?: string): ContentBlock[] {
  if (typeof content === 'string') return content.trim() ? [{ type: 'text', text: content }] : []
  if (!Array.isArray(content)) return []
  const blocks: ContentBlock[] = []
  for (const b of content) {
    const o = obj(b)
    if (!o) continue
    switch (o.type) {
      case 'text':
        if (typeof o.text === 'string' && o.text.trim()) blocks.push({ type: 'text', text: o.text })
        break
      case 'thinking':
        if (typeof o.thinking === 'string' && o.thinking.trim())
          blocks.push({ type: 'thinking', text: o.thinking })
        break
      case 'redacted_thinking':
        blocks.push({ type: 'thinking', text: '', redacted: true })
        break
      case 'tool_use':
      case 'server_tool_use': {
        const name = str(o.name) ?? 'tool'
        blocks.push({
          type: 'tool_use',
          id: str(o.id) ?? `tool-${blocks.length}`,
          name,
          input: o.input ?? {},
          label: toolLabel(name, o.input, cwd)
        })
        break
      }
      case 'image':
        blocks.push({ type: 'image', mediaType: str(obj(o.source)?.media_type) })
        break
      default:
        break
    }
  }
  return blocks
}

/**
 * Turn raw events into chat messages: consecutive assistant events that share a
 * message id are merged, and tool results are attached to their tool calls.
 */
export function buildMessages(events: RawEvent[], cwd?: string): ChatMessage[] {
  return buildMessagesWithRanges(events, cwd).messages
}

/**
 * Like buildMessages, plus the range of event indexes `[first, last]` each
 * message was built from (used to cut a session at a message).
 */
export function buildMessagesWithRanges(
  events: RawEvent[],
  cwd?: string
): { messages: ChatMessage[]; ranges: Map<string, [number, number]> } {
  const messages: ChatMessage[] = []
  const ranges = new Map<string, [number, number]>()
  const toolUses = new Map<string, Extract<ContentBlock, { type: 'tool_use' }>>()
  const assistantById = new Map<string, ChatMessage>()
  let counter = 0
  if (!cwd) cwd = events.map((e) => str(e.cwd)).find(Boolean)
  const nextId = (e: RawEvent): string => str(e.uuid) ?? `m${counter++}`

  const push = (m: ChatMessage, i: number): void => {
    messages.push(m)
    ranges.set(m.id, [i, i])
  }

  for (let i = 0; i < events.length; i++) {
    const e = events[i]
    const type = str(e.type)
    if (type === 'summary' || isSidechain(e)) continue
    const timestamp = validTimestamp(e.timestamp)

    if (type === 'system') {
      const text = str(e.content)
      const subtype = str(e.subtype)
      if (subtype === 'compact_boundary') {
        push(
          {
            id: nextId(e),
            role: 'system',
            kind: 'system',
            timestamp,
            blocks: [{ type: 'text', text: 'Conversation compacted' }]
          },
          i
        )
      } else if (text && e.isMeta !== true) {
        push(
          {
            id: nextId(e),
            role: 'system',
            kind: 'system',
            timestamp,
            blocks: [{ type: 'text', text }]
          },
          i
        )
      }
      continue
    }

    const role = roleOf(e)
    if (role === 'user') {
      const content = contentOf(e)
      if (e.isCompactSummary === true) {
        const text = textFromBlocks(content)
        if (text)
          push(
            {
              id: nextId(e),
              role: 'user',
              kind: 'compact',
              timestamp,
              blocks: [{ type: 'text', text }]
            },
            i
          )
        continue
      }
      if (e.isMeta === true) continue

      const blocks: ContentBlock[] = []
      let kind: ChatMessage['kind'] = 'prompt'
      const handleText = (raw: string): void => {
        const c = classifyUserText(raw)
        if (c.kind === 'noise' && !c.text) return
        if (c.kind === 'command' || c.kind === 'command-output') kind = c.kind
        blocks.push({ type: 'text', text: c.text })
      }
      if (typeof content === 'string') handleText(content)
      else if (Array.isArray(content)) {
        for (const b of content) {
          const o = obj(b)
          if (!o) continue
          if (o.type === 'text' && typeof o.text === 'string') handleText(o.text)
          else if (o.type === 'image')
            blocks.push({ type: 'image', mediaType: str(obj(o.source)?.media_type) })
          else if (o.type === 'tool_result') {
            const id = str(o.tool_use_id) ?? ''
            const result = toolResultOf(o, e)
            const use = toolUses.get(id)
            if (use) use.result = result
            else blocks.push({ type: 'tool_result', toolUseId: id, result })
          }
        }
      }
      if (blocks.length) push({ id: nextId(e), role: 'user', kind, timestamp, blocks }, i)
      continue
    }

    if (role === 'assistant') {
      const m = messageOf(e)
      const msgId = str(m?.id)
      const model = str(m?.model)
      const blocks = blocksFromAssistantContent(contentOf(e), cwd)
      for (const b of blocks) if (b.type === 'tool_use') toolUses.set(b.id, b)
      const existing = msgId ? assistantById.get(msgId) : undefined
      // Merge only into the most recent message, so ordering stays intact.
      if (existing && messages[messages.length - 1] === existing) {
        existing.blocks.push(...blocks)
        const r = ranges.get(existing.id)
        if (r) r[1] = i
        continue
      }
      if (!blocks.length) continue
      const msg: ChatMessage = {
        id: nextId(e),
        role: 'assistant',
        kind: 'response',
        timestamp,
        model: model && model !== '<synthetic>' ? model : undefined,
        blocks
      }
      if (msgId) assistantById.set(msgId, msg)
      push(msg, i)
    }
  }
  return { messages, ranges }
}
